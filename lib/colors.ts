export const getTypeStyle = (type?: string): TypeStyle => {
  if (!type) return POKEMON_TYPE_STYLES.normal;
  const lower = type.toLowerCase();
  return POKEMON_TYPE_STYLES[lower] || POKEMON_TYPE_STYLES.normal;
};

